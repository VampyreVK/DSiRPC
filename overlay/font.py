class PixelFont:
    """Renders strings to cached Surfaces. Colours are (r, g, b) tuples;
    shadow=None draws without a shadow. mini=True uses the 3x5 label font."""

    def __init__(self, mini=False):
        self._cache = {}
        self.mini = mini
        self.height = 5 if mini else 9

    def _glyph(self, ch):
        if self.mini:
            return _MINI.get(ch) or _MINI.get(ch.upper()) or _MINI[' ']
        return _glyph(ch)

    def width(self, text):
        if not text:
            return 0
        return sum(len(self._glyph(c)[0]) + SPACING for c in text) - SPACING

    def render(self, text, color, shadow=None):
        key = (text, color, shadow)
        surf = self._cache.get(key)
        if surf is not None:
            return surf
        w = self.width(text) + (1 if shadow else 0)
        h = self.height + (1 if shadow else 0)
        surf = pygame.Surface((max(1, w), h), pygame.SRCALPHA)
        passes = []
        if shadow:
            passes += [(shadow, 1, 0), (shadow, 0, 1), (shadow, 1, 1)]
        passes.append((color, 0, 0))
        for col, ox, oy in passes:
            x = 0
            for ch in text:
                rows = self._glyph(ch)
                for y, row in enumerate(rows):
                    for gx, px in enumerate(row):
                        if px == '#':
                            surf.set_at((x + gx + ox, y + oy), col)
                x += len(rows[0]) + SPACING
        if len(self._cache) > 2000:
            self._cache.clear()
        self._cache[key] = surf
        return surf

    def draw(self, target, text, pos, color, shadow=None, align='left'):
        surf = self.render(text, color, shadow)
        x, y = pos
        if align == 'right':
            x -= surf.get_width() - (1 if shadow else 0)
        elif align == 'center':
            x -= (surf.get_width() - (1 if shadow else 0)) // 2
        target.blit(surf, (x, y))
        return surf.get_width()
