# Characters Gen IV text uses that aren't drawn above, and what to show instead.
_FALLBACK = {'’': "'", '‘': "'", '“': '"', '”': '"', '–': '-', '—': '-'}


def _glyph(ch):
    ch = _FALLBACK.get(ch, ch)
    return _GLYPHS.get(ch) or _GLYPHS['?']


def text_width(text):
    if not text:
        return 0
    return sum(len(_glyph(c)[0]) + SPACING for c in text) - SPACING


